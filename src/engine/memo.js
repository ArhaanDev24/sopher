// Builds the quarterly capitalization memo as a Confluence page (storage format).
// This is the document a controller attaches to the close, and what an auditor reads first.
// Pure function of a schedule (from buildSchedule) and settings, so it is testable offline.

const STAGE_LABEL = {
  preliminary: 'Preliminary project',
  development: 'Application development',
  'post-implementation': 'Post-implementation',
};

/** Escapes text for Confluence storage format (XHTML). */
export function xml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const money = (n, currency) =>
  new Intl.NumberFormat('en-US', { style: 'currency', currency, minimumFractionDigits: 2, maximumFractionDigits: 2 }).format(n ?? 0);

const table = (headers, rows, { wide = false } = {}) => [
  wide ? '<table data-layout="full-width"><tbody>' : '<table><tbody>',
  `<tr>${headers.map((h) => `<th><p>${xml(h)}</p></th>`).join('')}</tr>`,
  ...rows.map((r) => `<tr>${r.map((c) => `<td><p>${c}</p></td>`).join('')}</tr>`),
  '</tbody></table>',
].join('');

const panel = (type, text) =>
  `<ac:structured-macro ac:name="${type}"><ac:rich-text-body><p>${text}</p></ac:rich-text-body></ac:structured-macro>`;

export function memoTitle(projectKey, quarter) {
  return `Software capitalization memo: ${projectKey} ${quarter}`;
}

/**
 * @param {object} schedule result of buildSchedule, plus projectKey
 * @param {object} settings merged settings
 * @param {{ generatedAt?: Date, siteUrl?: string }} [opts]
 * @returns {{ title: string, body: string }}
 */
export function buildMemo(schedule, settings, { generatedAt = new Date(), siteUrl = '' } = {}) {
  const cur = schedule.currency;
  const m = (n) => xml(money(n, cur));
  const t = schedule.totals;
  const issueLink = (key) => (siteUrl ? `<a href="${xml(`${siteUrl}/browse/${key}`)}">${xml(key)}</a>` : xml(key));
  const assets = schedule.assets.filter((a) => a.epicKey);
  const unlinked = schedule.assets.find((a) => !a.epicKey);

  const parts = [
    schedule.close
      ? panel('note', `<strong>Quarter closed</strong> on ${xml(String(schedule.close.at).slice(0, 10))}${schedule.close.byName ? ` by ${xml(schedule.close.byName)}` : ''}. ${schedule.drift?.hasDrift ? 'Figures below are live. Changes since close are listed under Post-close adjustments.' : 'No changes since close.'}`)
      : '',
    panel('info', `<strong>${schedule.close ? 'Closed quarter memo.' : 'Draft for controller review.'}</strong> Generated by Sopher on ${xml(generatedAt.toISOString().slice(0, 10))} from Jira work logged in project ${xml(schedule.projectKey)}. Figures are cost (logged hours × loaded rate). Every classification can be overridden in Jira with a recorded reason.`),

    '<h2>Summary</h2>',
    table(['Measure', schedule.quarter], [
      ['Capitalized development cost', m(t.capex)],
      ['Expensed cost', m(t.opex)],
      ['Capitalization rate', `${Math.round(t.capitalizationRate * 100)}%`],
      ['Amortization expense', m(t.amortization)],
      ['Net book value at quarter end', m(t.netBookValue)],
      ['Operating income effect (capitalized minus amortization)', m(t.operatingIncomeEffect ?? (t.capex - t.amortization))],
    ]),

    '<h2>Software assets</h2>',
    assets.length === 0
      ? '<p>No epics in this project.</p>'
      : table(
        ['Asset (epic)', 'Stage at quarter end', 'Authorized', 'Placed in service', 'Capitalized this quarter', 'Expensed this quarter', 'Capitalized to date', 'Amortization', 'Net book value', 'Evidence (Teamwork Graph)'],
        assets.map((a) => [
          `${issueLink(a.epicKey)} ${xml(a.summary)}`,
          xml(STAGE_LABEL[a.stageAtQuarterEnd] ?? '—'),
          xml(a.authorizedAt ?? 'Not authorized'),
          xml(a.releasedAt ? `${a.releasedAt}${a.releaseSource === 'deployment' ? ' (first production deployment)' : ''}` : 'Not released'),
          m(a.capex), m(a.opex), m(a.capexToDate), m(a.amortization), m(a.netBookValue),
          xml(a.evidenceText ?? 'Not checked'),
        ]),
        { wide: true },
      ),
    unlinked && unlinked.issueCount > 0
      ? `<p>Work not linked to any epic: ${m(unlinked.opex)} expensed this quarter, pending review.</p>`
      : '',

    schedule.drift?.hasDrift
      ? [
        '<h2>Post-close adjustments</h2>',
        `<p>Since the quarter was closed: capitalized ${m(schedule.drift.totals.capexDelta)}, expensed ${m(schedule.drift.totals.opexDelta)}, amortization ${m(schedule.drift.totals.amortizationDelta)}.</p>`,
        table(['Issue', 'Change', 'Capitalized (closed → now)', 'Expensed (closed → now)'], schedule.drift.changes.map((c) => [
          `${issueLink(c.key)} ${xml(c.summary ?? '')}`,
          xml(c.kind),
          `${m(c.before.capex)} → ${m(c.after.capex)}`,
          `${m(c.before.opex)} → ${m(c.after.opex)}`,
        ])),
      ].join('')
      : '',

    '<h2>Items needing review</h2>',
    schedule.reviewQueue.length === 0
      ? '<p>None. All work this quarter was classified with high or medium confidence.</p>'
      : table(['Issue', 'Confidence', 'Reason'], schedule.reviewQueue.map((r) => [
        `${issueLink(r.key)} ${xml(r.summary)}`,
        xml(r.confidence),
        xml(r.reasons[0]),
      ])),

    t.estimatedCost > 0
      ? panel('warning', `${m(t.estimatedCost)} of this quarter's cost is based on original estimates because no time was logged. Confirm actual effort before close.`)
      : '',

    '<h2>Method</h2>',
    '<ul>',
    '<li><p>Treatment follows the internal-use software stages of ASC 350-40. Work in the preliminary project stage (before authorization) and the post-implementation stage (after release) is expensed. Work in the application development stage is capitalized.</p></li>',
    '<li><p>Under ASU 2025-06, which removes the stage wording, the authorization date recorded on each epic marks when the project met the capitalization threshold (authorized, funded and probable to be completed), and the placed-in-service date marks when the software was ready for its intended use. The same boundaries apply.</p></li>',
    '<li><p>Each time log is classified on its own date, so one issue can be partly capitalized and partly expensed.</p></li>',
    `<li><p>Bugs, support and maintenance (issue types ${xml(settings.expenseIssueTypes.join(', '))}; labels ${xml(settings.maintenanceLabels.join(', '))}) and research or spikes (labels ${xml(settings.researchLabels.join(', '))}) are always expensed.</p></li>`,
    `<li><p>Cost uses a loaded hourly rate of ${m(settings.defaultHourlyRate)} unless a person has their own rate.</p></li>`,
    '<li><p>Evidence comes from Atlassian Teamwork Graph: pull requests, deployments and goals linked to each epic. If an epic has no release date in Jira, its first successful production deployment is used as the placed-in-service date.</p></li>',
    `<li><p>Capitalized cost is amortized straight-line over ${xml(settings.usefulLifeMonths)} months, starting the month after the asset is placed in service (its release).</p></li>`,
    '</ul>',

    '<h2>Sign-off</h2>',
    table(['Role', 'Name', 'Date'], [['Prepared by', '', ''], ['Reviewed by (controller)', '', '']]),
  ];

  return { title: memoTitle(schedule.projectKey, schedule.quarter), body: parts.filter(Boolean).join('') };
}
