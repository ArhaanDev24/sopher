// Publishes the capitalization memo to Confluence (REST API v2).
// Re-running for the same project and quarter updates the existing page instead of creating
// a duplicate, so the memo can be regenerated after overrides.

import api, { route } from '@forge/api';

async function confluence(requester, path, { method = 'GET', body } = {}) {
  const res = await requester.requestConfluence(path, {
    method,
    headers: { Accept: 'application/json', 'Content-Type': 'application/json' },
    body: body && JSON.stringify(body),
  });
  const text = await res.text();
  const data = text ? JSON.parse(text) : {};
  if (!res.ok) {
    const detail = data.errors?.map((e) => e.title ?? e.detail).join(' ') || data.message || text.slice(0, 200);
    if (res.status === 404 || res.status === 403) {
      throw new Error(`Confluence returned ${res.status} (${detail}). Check that Sopher is installed in Confluence and that you can edit the space.`);
    }
    throw new Error(`Confluence request failed (${res.status}): ${detail}`);
  }
  return data;
}

async function spaceByKey(requester, spaceKey) {
  const data = await confluence(requester, route`/wiki/api/v2/spaces?keys=${spaceKey}&limit=1`);
  const space = data.results?.[0];
  if (!space) throw new Error(`Confluence space "${spaceKey}" was not found, or you can't see it.`);
  return space;
}

const pageUrl = (page, fallbackBase) => {
  const base = page._links?.base ?? fallbackBase ?? '';
  return page._links?.webui ? `${base}${page._links.webui}` : null;
};

/**
 * Creates or updates a page titled `title` in the space with key `spaceKey`.
 * @returns {{ id: string, url: string|null, created: boolean, version: number }}
 */
export async function publishPage({ spaceKey, title, body, siteUrl }, requester = api.asUser()) {
  const space = await spaceByKey(requester, spaceKey);
  const found = await confluence(
    requester,
    route`/wiki/api/v2/spaces/${space.id}/pages?title=${title}&status=current&limit=1`,
  );
  const existing = found.results?.[0];
  const representation = { representation: 'storage', value: body };
  const wikiBase = siteUrl ? `${siteUrl}/wiki` : undefined;

  if (existing) {
    const current = await confluence(requester, route`/wiki/api/v2/pages/${existing.id}`);
    const version = (current.version?.number ?? 1) + 1;
    const page = await confluence(requester, route`/wiki/api/v2/pages/${existing.id}`, {
      method: 'PUT',
      body: { id: existing.id, status: 'current', title, body: representation, version: { number: version, message: 'Regenerated by Sopher' } },
    });
    return { id: page.id, url: pageUrl(page, wikiBase), created: false, version };
  }

  const page = await confluence(requester, route`/wiki/api/v2/pages`, {
    method: 'POST',
    body: { spaceId: space.id, status: 'current', title, body: representation },
  });
  return { id: page.id, url: pageUrl(page, wikiBase), created: true, version: 1 };
}
